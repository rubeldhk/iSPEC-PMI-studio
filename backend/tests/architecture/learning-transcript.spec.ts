/**
 * `T2415` (EPIC-048, Constitution XI **Tier 2**, `SC-LRN-007`, analysis finding
 * `C2`) — the Governed Learning transcript conforms.
 *
 * Asserts `docs/uat/EPIC-048-transcript.md` **exists**, **names the run** — the
 * harness that generated it, the instant and the stack — was **generated rather
 * than authored** (the harness's own header and timestamped steps, no
 * credential), and records the journey quickstart Q6, Q15, Q19, Q28 and Q29 name:
 * the Decision Inbox and Context → Knowledge reached through primary
 * navigation, a superseding candidate approved — narrowed — at 360px with the
 * current and proposed statements side by side, the history read in order, and
 * **one decision of a candidate with five evidence items timed under two
 * minutes**, from opening the Inbox entry to the decision recorded.
 *
 * **Known-red until the journey is run** (`governance/known-red.json`). The
 * harness, `e2e/tests/epic-048-learning.spec.ts`, is authored and writes the
 * transcript itself, but the run needs the reference-local stack and a seeded
 * user's password, which an agent does not hold. Typing the transcript instead
 * would fabricate exactly the evidence this check exists to test for (`RK-8`).
 * The planted cases below prove it can tell a conforming transcript from a
 * hand-written one, so it is not decoration while it waits.
 */
import { existsSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

const here = dirname(fileURLToPath(import.meta.url));
const TRANSCRIPT = resolve(here, '../../../docs/uat/EPIC-048-transcript.md');

/** `SC-LRN-007` — one decision, five evidence items, under two minutes. */
const LIMIT_MS = 120_000;

export function transcriptFindings(text: string): string[] {
  const findings: string[] = [];
  if (!/^# EPIC-048 — Governed Learning transcript \(Constitution XI Tier 2\)/m.test(text)) findings.push('no harness header');
  if (!/\*\*Generated by\*\* `e2e\/tests\/epic-048-learning\.spec\.ts` on \d{4}-\d{2}-\d{2}T/.test(text)) {
    findings.push('does not name the harness and the time it ran');
  }
  if (!/\*\*Stack\*\*: \S/.test(text)) findings.push('does not name the stack');
  const steps = text.match(/^- \d{4}-\d{2}-\d{2}T[\d:.]+Z /gm) ?? [];
  if (steps.length < 8) findings.push(`has ${steps.length} timestamped steps; the journey has at least eight`);
  for (const must of [/primary navigation/i, /Decision Inbox/, /Context → Knowledge/, /360px/, /side by side/i, /superseded/i, /history/i, /five evidence items/i]) {
    if (!must.test(text)) findings.push(`never records ${must.source}`);
  }
  const timed = /decided in (\d+) ms/i.exec(text);
  if (timed === null) findings.push('records no timed decision (SC-LRN-007)');
  else if (Number(timed[1]) >= LIMIT_MS) findings.push(`the timed decision took ${timed[1]} ms, not under ${LIMIT_MS} (SC-LRN-007)`);
  if (/password\s*[:=]\s*\S+/i.test(text) || /pmi_ct_[A-Za-z0-9_-]{20,}/.test(text)) findings.push('carries a credential');
  return findings;
}

describe('T2415 · the Governed Learning transcript (XI Tier 2)', () => {
  it('exists — generated by running e2e/tests/epic-048-learning.spec.ts against a stack', () => {
    expect(existsSync(TRANSCRIPT), `no transcript at ${TRANSCRIPT}; the Tier 2 journey has not been run`).toBe(true);
  });

  it('names the run, was generated rather than authored, and records the journey', () => {
    expect(transcriptFindings(readFileSync(TRANSCRIPT, 'utf8'))).toEqual([]);
  });
});

describe('T2415 · the check can tell generated from authored', () => {
  const generated = [
    '# EPIC-048 — Governed Learning transcript (Constitution XI Tier 2)',
    '',
    '**Generated by** `e2e/tests/epic-048-learning.spec.ts` on 2026-10-11T12:00:00.000Z · **Stack**: reference local',
    '',
    '- 2026-10-11T12:00:00.000Z Signed in.',
    '- 2026-10-11T12:00:01.000Z An agent submitted a candidate citing five evidence items: pending-review.',
    '- 2026-10-11T12:00:02.000Z Reached the Decision Inbox through primary navigation.',
    '- 2026-10-11T12:00:30.000Z Opened the entry and approved it: decided in 28000 ms (SC-LRN-007).',
    '- 2026-10-11T12:00:31.000Z At 360px, a superseding candidate shows current and proposed side by side.',
    '- 2026-10-11T12:00:32.000Z Narrowed to one project and approved: version 2.',
    '- 2026-10-11T12:00:33.000Z Reached Context → Knowledge through primary navigation; filtered superseded.',
    '- 2026-10-11T12:00:34.000Z Opened the history: v1, v2, in order.',
  ].join('\n');

  it('passes a planted generated transcript', () => {
    expect(transcriptFindings(generated)).toEqual([]);
  });

  it.each([
    ['a hand-written summary', '# Learning UAT\n\nApproved a candidate, looked at history. Fine.'],
    ['a transcript naming no stack', generated.replace(/\*\*Stack\*\*: reference local/, '')],
    ['a transcript with too few steps', generated.split('\n').slice(0, 8).join('\n')],
    ['a transcript with no timed decision', generated.replace(/decided in 28000 ms/, 'decided')],
    ['a decision slower than two minutes', generated.replace(/decided in 28000 ms/, 'decided in 125000 ms')],
    ['a transcript never at 360px', generated.replace(/At 360px, /, '')],
    ['a transcript carrying a password', `${generated}\n- 2026-10-11T12:00:35.000Z password: hunter2`],
  ])('flags %s', (_label, text) => {
    expect(transcriptFindings(text).length).toBeGreaterThan(0);
  });
});
