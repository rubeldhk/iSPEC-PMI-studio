/**
 * `T2232` (EPIC-039, `R-039-16`) — the Integrations transcript conforms.
 * Constitution XI Tier 2.
 *
 * Asserts `docs/uat/EPIC-039-m1-transcript.md`, **once it exists**, names the
 * harness that generated it, the instant and the stack; carries distinct,
 * ordered ISO-timestamped steps; covers every stage of the walk — navigation,
 * `pmi-studio` first, the unhealthy reason, the refused resolution's
 * per-candidate explanation, no configuration control, 360 px, and
 * `SC-HUB-007`'s question answered from the screen; and holds no credential.
 *
 * **Skipped while the file is absent** (`R-039-16`'s decision): the walk has
 * not been run (`T2233`), and this Epic records that as owed in its closing
 * report rather than as a known-red. A skipped check is reported as skipped,
 * never as passed.
 *
 * ## The honest limit
 *
 * Nothing here can prove the file was produced by a run rather than typed —
 * as `change-room-transcript.spec.ts` says of its own. What it does is make
 * typing one as much work as running the walk, and easier to get wrong. The
 * planted cases below show it can tell a conforming transcript from a
 * hand-written one, so it is not decoration while it waits.
 */
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { REPO_ROOT } from './helpers';

const TRANSCRIPT = join(REPO_ROOT, 'docs', 'uat', 'EPIC-039-m1-transcript.md');

const STAGES: readonly [string, RegExp][] = [
  ['navigation', /Opened \*\*Integrations\*\* from the shell navigation/],
  ['pmi-studio first', /\*\*pmi-studio\*\* is listed first/],
  ['the unhealthy reason', /\*\*unhealthy — \S+/],
  ['the refused resolution explained', /refused resolution explains each candidate/],
  ['no configuration control', /No configuration control/],
  ['360 px', /\*\*360 px\*\*/],
  ['SC-HUB-007 answered from the screen', /\*\*SC-HUB-007\*\*[\s\S]*Answered from the screen alone/],
];

export function transcriptFindings(text: string): string[] {
  const findings: string[] = [];
  if (!/^# EPIC-039 — Integrations transcript \(Constitution XI Tier 2\)/m.test(text)) findings.push('no harness header');
  if (!/\*\*Generated by\*\* `e2e\/tests\/epic-039-m1\.spec\.ts` on \d{4}-\d{2}-\d{2}T/.test(text)) findings.push('does not name the harness and the time it ran');
  if (!/\*\*Stack\*\*: \S/.test(text)) findings.push('does not name the stack');
  const stamps = [...text.matchAll(/^- (\d{4}-\d{2}-\d{2}T[\d:.]+Z) /gm)].map((m) => m[1]!);
  if (stamps.length < 10) findings.push(`has ${stamps.length} timestamped steps; the walk has at least ten`);
  if (new Set(stamps).size !== stamps.length) findings.push('repeats a timestamp');
  const times = stamps.map((s) => Date.parse(s));
  if (times.some((v, i) => i > 0 && v < times[i - 1]!)) findings.push('steps are not in time order');
  for (const [stage, pattern] of STAGES) if (!pattern.test(text)) findings.push(`never records ${stage}`);
  if (/password\s*[:=]\s*\S+/i.test(text) || /pmi_ct_/.test(text) || /pmi-canary-/.test(text)) findings.push('carries a credential or canary');
  return findings;
}

describe.skipIf(!existsSync(TRANSCRIPT))('T2232 · the Integrations transcript (XI Tier 2) — present only once T2233 has run', () => {
  it('names the run, covers every stage, and holds no credential', () => {
    expect(transcriptFindings(readFileSync(TRANSCRIPT, 'utf8'))).toEqual([]);
  });
});

describe('T2232 · the check can tell generated from authored', () => {
  const step = (i: number, text: string): string => `- 2026-10-16T12:00:${String(i).padStart(2, '0')}.${String(100 + i)}Z ${text}`;
  const generated = [
    '# EPIC-039 — Integrations transcript (Constitution XI Tier 2)',
    '',
    '**Generated by** `e2e/tests/epic-039-m1.spec.ts` on 2026-10-16T12:00:20.000Z · **Stack**: reference local',
    '',
    step(0, 'Stack: **reference local**'),
    step(1, 'Signed in (credential withheld).'),
    step(2, 'Set up through the API.'),
    step(3, 'Requested ReadBuildStatus as room:change: **refused** (no-eligible-adapter).'),
    step(4, 'The health scheduler checked fixture-ci for the project: unhealthy.'),
    step(5, 'Opened **Integrations** from the shell navigation.'),
    step(6, '**pmi-studio** is listed first (FR-HUB-021).'),
    step(7, 'Fixture CI reads **unhealthy — provider-unreachable**, in words.'),
    step(8, 'Opened Fixture CI: the refused resolution explains each candidate — "fixture-ci — health-unhealthy".'),
    step(9, 'No configuration control on the screen; it says configuration is through the API.'),
    step(10, 'At **360 px** the list reads without horizontal scrolling.'),
    step(11, '**SC-HUB-007** — "…" Answered from the screen alone: connected to pmi-studio, Fixture CI.'),
  ].join('\n');

  it('passes a planted generated transcript', () => {
    expect(transcriptFindings(generated)).toEqual([]);
  });

  it.each([
    ['a hand-written summary', '# Integrations UAT\n\nEverything was healthy. Looked fine.'],
    ['a transcript naming no stack', generated.replace('**Stack**: reference local', '')],
    ['a transcript with too few steps', generated.split('\n').slice(0, 9).join('\n')],
    ['a transcript missing the 360 px stage', generated.replace('At **360 px**', 'At full width')],
    ['a transcript with a repeated instant', generated.replace('12:00:07.107Z', '12:00:06.106Z')],
    ['a transcript out of time order', generated.replace('12:00:11.111Z', '11:59:00.000Z')],
    ['a transcript carrying a connector credential', `${generated}\n${step(12, 'token pmi_ct_abcdef')}`],
  ])('flags %s', (_label, text) => {
    expect(transcriptFindings(text).length).toBeGreaterThan(0);
  });
});
